const lv_image_dsc_t *weather_get_icon(weather_icon_t icon)
{
    switch (icon) {
        case WEATHER_ICON_CLEAR_DAY:
            return &icon_clear_day;
        case WEATHER_ICON_CLEAR_NIGHT:
            return &icon_clear_night;
        case WEATHER_ICON_PARTLY_CLOUDY_DAY:
        case WEATHER_ICON_PARTLY_CLOUDY_NIGHT:
            return &icon_partly_cloudy;
        case WEATHER_ICON_CLOUDY:
            return &icon_cloudy;
        case WEATHER_ICON_RAIN_LIGHT:
        case WEATHER_ICON_RAIN_HEAVY:
            return &icon_rain;
        case WEATHER_ICON_SNOW_LIGHT:
        case WEATHER_ICON_SNOW_HEAVY:
            return &icon_snow;
        case WEATHER_ICON_THUNDERSTORM:
            return &icon_thunderstorm;
        case WEATHER_ICON_FOG:
            return &icon_fog;
        case WEATHER_ICON_WIND:
            return &icon_wind;
        default:
            return &icon_unknown;
    }
}

const char *weather_get_description(weather_icon_t icon)
{
    switch (icon) {
        case WEATHER_ICON_CLEAR_DAY:
            return "Clear";
        case WEATHER_ICON_CLEAR_NIGHT:
            return "Clear night";
        case WEATHER_ICON_PARTLY_CLOUDY_DAY:
            return "Partly cloudy";
        case WEATHER_ICON_PARTLY_CLOUDY_NIGHT:
            return "Partly cloudy";
        case WEATHER_ICON_CLOUDY:
            return "Cloudy";
        case WEATHER_ICON_RAIN_LIGHT:
            return "Light rain";
        case WEATHER_ICON_RAIN_HEAVY:
            return "Heavy rain";
        case WEATHER_ICON_SNOW_LIGHT:
            return "Light snow";
        case WEATHER_ICON_SNOW_HEAVY:
            return "Heavy snow";
        case WEATHER_ICON_THUNDERSTORM:
            return "Thunderstorm";
        case WEATHER_ICON_FOG:
            return "Fog";
        case WEATHER_ICON_WIND:
            return "Windy";
        default:
            return "Unknown";
    }
}
